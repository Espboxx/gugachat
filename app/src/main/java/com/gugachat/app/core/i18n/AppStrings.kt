enum class AppLanguage(val tag: String, val displayName: String) {
    ZH("zh", "简体中文"),
    EN("en", "English");

    companion object {
        fun fromTag(tag: String?): AppLanguage =
            if (tag?.lowercase()?.startsWith("en") == true) EN else ZH
    }
}

fun String.fmt(vararg args: Pair<String, Any?>): String {
    var out = this
    for ((k, v) in args) {
        out = out.replace("{$k}", v?.toString().orEmpty())
    }
    return out
}

